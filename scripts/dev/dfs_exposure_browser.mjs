// Production controls with local API fixtures; real optimizer behavior is covered by pytest.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readPortfolioBackup } from "../../frontend/src/dfsPortfolioBackup.js";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const require = createRequire(path.join(root, "frontend/package.json"));
const { chromium } = require("playwright");
const base = process.env.DFS_BROWSER_BASE || "http://127.0.0.1:5173";
const output = path.join(root, "outputs/dfs-exposure");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  for (const width of [1280, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 }, acceptDownloads: true });
    const errors = []; page.on("pageerror", e => errors.push(e.message));
    await page.goto(`${base}/test-fixtures/dfs-portfolio.html?exposure=1`);
    await page.getByRole("spinbutton", { name: "Lineups", exact: true }).fill("3");
    await page.locator(".dfw-build-button").click();
    await page.getByLabel("Batch label", { exact: true }).fill("First approved batch");
    await page.getByRole("button", { name: "Add current build to portfolio", exact: true }).click();
    await page.getByText("3 / 150 unique · 3 collected", { exact: false }).waitFor();
    await page.getByRole("button", { name: "Exposure", exact: true }).click();
    const editor = page.locator(".dfw-exposure-editor");
    const maximum = page.getByLabel("Portfolio maximum: Example 1", { exact: true });
    await maximum.fill("30"); await maximum.press("Tab");
    assert.match(await maximum.locator("..").textContent(), /45 of 150/);
    await page.getByRole("button", { name: /^Enter maximum as:/ }).click();
    await page.getByRole("option", { name: "Lineup count", exact: true }).click();
    await page.waitForFunction(() => document.querySelector('input[aria-label="Portfolio maximum: Example 1"]')?.value === "45");
    await maximum.fill("44"); await maximum.press("Tab");
    await page.getByRole("button", { name: /^Enter maximum as:/ }).click();
    await page.getByRole("option", { name: "% of 150", exact: true }).click();
    await maximum.focus(); await maximum.press("Tab");
    await page.getByRole("button", { name: /^Enter maximum as:/ }).click();
    await page.getByRole("option", { name: "Lineup count", exact: true }).click();
    await page.waitForFunction(() => document.querySelector('input[aria-label="Portfolio maximum: Example 1"]')?.value === "44");
    await maximum.fill("4"); await maximum.press("Tab");
    await page.getByLabel("Select exposure: Example 2", { exact: true }).check();
    await page.getByLabel("Select exposure: Example 3", { exact: true }).check();
    await page.getByLabel("Maximum for selected players", { exact: true }).fill("30");
    await page.getByRole("button", { name: "Apply maximum", exact: true }).click();
    await page.waitForFunction(() => document.querySelector('input[aria-label="Portfolio maximum: Example 2"]')?.value === "30");
    await page.getByRole("button", { name: "Clear selection", exact: true }).click();
    await page.getByLabel("Use portfolio limits for next build", { exact: true }).check();
    // A lock cannot bypass the remaining count, and the rejected build makes no API call.
    await page.getByRole("button", { name: "Player pool", exact: true }).click();
    await page.getByRole("button", { name: "Lock Example 1", exact: true }).click();
    const before = await page.evaluate(() => window.__portfolioFixture.requests.length);
    await page.locator(".dfw-build-button").click();
    await page.getByText(/Example 1 is locked for 3 lineups but has only 1/).waitFor();
    assert.equal(await page.evaluate(() => window.__portfolioFixture.requests.length), before);
    await page.getByRole("button", { name: "Lock Example 1", exact: true }).click();
    const game = page.locator(".dfw-matchup-card").first();
    await game.getByRole("button", { name: /^Choose stacks for/ }).click();
    assert.equal(await game.locator(".dfw-stack-picker").evaluate(el => el.open), true);
    await game.getByRole("checkbox", { name: "Example 1 · KC", exact: true }).check();
    await game.getByRole("checkbox", { name: "Other quarterback · BUF", exact: true }).check();
    await game.locator(".dfw-stack-choice").filter({ has: page.getByRole("checkbox", { name: "Example 1 · KC", exact: true }) }).locator(".dfw-stack-inclusions > summary").click();
    await game.getByRole("checkbox", { name: "Example 5 WR · With this QB", exact: true }).check();
    await page.locator(".dfw-build-button").click();
    await page.getByLabel("Batch label", { exact: true }).fill("Remaining allowances");
    await page.getByRole("button", { name: "Add current build to portfolio", exact: true }).click();
    await page.getByText("6 / 150 unique · 6 collected", { exact: false }).waitFor();
    const request = await page.evaluate(() => window.__portfolioFixture.requests.at(-1));
    assert.equal(request.player_maximum_counts.p1, 1);
    assert.equal(request.player_maximum_counts.p2, 3);
    assert.deepEqual(request.stack_choices, [{ game_id: "kc-buf", qb_id: "p1", player_ids: ["p5"] }, { game_id: "kc-buf", qb_id: "p181", player_ids: [] }]);
    assert.equal(request.stack_game_weights[0].weight, 1);
    assert.deepEqual(request.locked_player_ids, []);
    await page.getByRole("button", { name: "Exposure", exact: true }).click();
    const row = editor.getByRole("row").filter({ has: page.getByLabel("Select exposure: Example 1", { exact: true }) });
    assert.match(await row.textContent(), /4.*66\.7%.*4 of 150.*0/);
    await page.getByLabel("Find player exposure", { exact: true }).fill("Example 1");
    await editor.screenshot({ path: path.join(output, `exposure-${width}.png`) });
    await game.screenshot({ path: path.join(output, `stacks-${width}.png`) });
    const pending = page.waitForEvent("download");
    await page.getByRole("button", { name: "Download portfolio backup", exact: true }).click();
    const download = await pending, filename = path.join(output, `backup-${width}.json`);
    await download.saveAs(filename);
    const backup = readPortfolioBackup(await readFile(filename, "utf8"));
    assert.equal(backup.batches[0].lineups[0].lineup[0].player_id, "p1");
    assert.equal(backup.batches[1].settings.player_maximum_counts.p1, 1);
    assert.equal(backup.batches[1].settings.portfolio_exposure_plan.maximum_counts.p1, 4);
    await page.reload();
    await page.getByLabel("Restore portfolio backup", { exact: true }).setInputFiles(filename);
    await page.getByText("6 / 150 unique · 6 collected", { exact: false }).waitFor();
    assert.equal(await page.evaluate(() => window.__portfolioFixture.requests.length), 0);
    await page.getByRole("button", { name: "Exposure", exact: true }).click();
    await page.getByRole("button", { name: /^Show:/ }).click();
    await page.getByRole("option", { name: "Limited players", exact: true }).click();
    assert.equal(await page.locator(".dfw-exposure-table tbody tr").count(), 3);
    assert.deepEqual(errors, []);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert.equal(overflow, false);
    const tableFits = await page.locator(".dfw-exposure-scroll").evaluate(el => el.scrollWidth <= el.clientWidth + 1);
    assert.equal(tableFits, true, "the exposure editor should show every column without horizontal scrolling");
    console.log(`PASS exposure/stack controls, remaining budgets, lock rejection, immutable backup/restore, no overflow at ${width}`);
    await page.close();
  }
} finally { await browser.close(); }
